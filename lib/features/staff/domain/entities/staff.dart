class Staff {
  final int id;
  final String? username;
  final String? password;
  final String? email;
  final int? age;
  final int? height;
  final String? phone;
  final String? uid;
  final String? roleName;

  Staff({
    required this.id,
    this.username,
    this.password,
    this.email,
    this.age,
    this.height,
    this.phone,
    this.uid,
    this.roleName,
  });

}
